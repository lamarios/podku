@Service
public class PodcastService {
  private final Logger log = LogManager.getLogger();
  private final PodcastRepository podcastRepository;
  private final EpisodeService episodeService;
  private final PlatformTransactionManager platformTransactionManager;
  private final EpisodeRepository episodeRepository;
  private final int episodeCacheCount;
  private final Path episodeCacheFolder;
  private final PodcastParser podcastParser;
  private final WhisperService whisperService;

  /**
   * Constructs the PodcastService with repositories, services, and local cache configuration.
   *
   * @param podcastRepository podcast entity repository
   * @param episodeService episode service for processing
   * @param platformTransactionManager transaction manager
   * @param episodeRepository episode entity repository
   * @param episodeCacheFolder path to local episode cache
   * @param episodeCacheCount number of recent episodes to cache
   * @param podcastParser XML feed parser
   * @param whisperService transcription service
   *     <p>javadoc generated by AI
   */
  @Autowired
  public PodcastService(
      PodcastRepository podcastRepository,
      EpisodeService episodeService,
      @Qualifier("transactionManager") PlatformTransactionManager platformTransactionManager,
      EpisodeRepository episodeRepository,
      @Value("${podku.episodes.cache-dir:./episode-cache}") String episodeCacheFolder,
      @Value("${podku.episodes.cache-count:0}") String episodeCacheCount,
      PodcastParser podcastParser,
      WhisperService whisperService) {
    this.podcastRepository = podcastRepository;
    this.episodeService = episodeService;
    this.platformTransactionManager = platformTransactionManager;
    this.episodeRepository = episodeRepository;
    this.episodeCacheCount = Integer.parseInt(episodeCacheCount);

    Path p = Path.of(episodeCacheFolder);
    if (!p.toFile().exists()) {
      if (!p.toFile().mkdirs()) {
        log.info("Episode cache folder already exists");
      }
    }

    this.episodeCacheFolder = p;
    this.podcastParser = podcastParser;
    this.whisperService = whisperService;
  }

  /**
   * Retrieves all subscribed podcasts sorted alphabetically by name.
   *
   * @return list of subscribed podcasts
   *     <p>javadoc generated by AI
   */
  @Transactional(readOnly = true)
  public List<Podcast> getPodcasts() {
    return podcastRepository.findAll(Sort.by(Sort.Direction.ASC, "name"));
  }

  /**
   * Subscribes to a new podcast given search result information, fetching its feed and starting
   * episode processing.
   *
   * @param result search result with feed URL and metadata
   * @return newly created podcast entity, or null if already subscribed
   *     <p>javadoc generated by AI
   */
  public Podcast subscribe(SearchResult result) {
    if (result.getFeedUrl() != null) {
      Optional<Podcast> alreadySubscribed = podcastRepository.findFirstByUrl(result.getFeedUrl());
      if (alreadySubscribed.isPresent()) {
        return null;
      } else {
        Podcast podcast = new Podcast();
        podcast.setUrl(result.getFeedUrl());
        String name = result.getCollectionName();

        podcast.setName(name);
        podcast.setArtworkUrl(result.getArtworkUrl());

        Podcast parsedPodcast = podcastParser.parseUrl(podcast);

        Podcast saved =
            TransactionHelper.doInNewTransaction(
                platformTransactionManager, false, () -> podcastRepository.save(parsedPodcast));
        episodeService
            .processPodcast(saved.getId())
            .thenAccept(_ -> whisperService.processEpisodeCron());
        return saved;
      }
    } else {
      return null;
    }
  }

  /**
   * Retrieves a single podcast by its string UUID.
   *
   * @param id podcast UUID string
   * @return podcast or null if not found
   *     <p>javadoc generated by AI
   */
  @Transactional(readOnly = true)
  public Podcast getPodcast(String id) {
    return podcastRepository.findById(UUID.fromString(id)).orElse(null);
  }

  /**
   * Unsubscribes from and deletes a podcast by its string UUID.
   *
   * @param id podcast UUID string
   *     <p>javadoc generated by AI
   */
  @Transactional
  public void unsubscribe(String id) {
    podcastRepository.deletePodcastById(UUID.fromString(id));
  }

  /**
   * Hourly scheduled job that refreshes all subscribed podcast feeds, updates episodes, and
   * downloads audio.
   *
   * <p>Episode processing (chapters/transcripts) and whisper run afterwards on the background
   * queue; this method does not wait for them so the (single) scheduler thread stays available for
   * the other scheduled jobs such as the websocket pings.
   */
  @Scheduled(fixedRate = 1, timeUnit = TimeUnit.HOURS)
  public void refreshPodcasts() {
    List<UUID> toProcess =
        TransactionHelper.doInNewTransaction(
            platformTransactionManager, true, podcastRepository::findAllIds);

    for (var p : toProcess) {
      try {
        refreshPodcast(p);
      } catch (Exception e) {
        log.error("Failed to refresh podcast: {}, continuing process", p, e);
      }
    }

    log.info("Episode refresh done");
    try {
      downloadEpisodes();
    } catch (Exception e) {
      log.error("Error while downloading episodes", e);
    }

    episodeService
        .processUnprocessedEpisodes()
        .thenRun(whisperService::processEpisodeCron)
        .exceptionally(
            e -> {
              log.error("Failed to process episodes after refresh", e);
              return null;
            });
  }

  /**
   * Refreshes a single podcast from its feed.
   *
   * <p>The feed is downloaded and parsed (including the artwork color extraction) without any
   * transaction open, into a fresh object graph. Only then is the stored podcast loaded and
   * updated, in a short transaction, by {@link PodcastFeedMerger}.
   *
   * @param podcastId the podcast to refresh
   */
  public void refreshPodcast(UUID podcastId) {
    FeedLocation feed =
        TransactionHelper.doInNewTransaction(
            platformTransactionManager,
            true,
            () ->
                podcastRepository
                    .findById(podcastId)
                    .map(p -> new FeedLocation(p.getUrl(), p.getEtag(), p.getLastModified()))
                    .orElse(null));
    if (feed == null) {
      log.info("Podcast {} no longer exists, skipping refresh", podcastId);
      return;
    }

    log.info("Refreshing podcast {}", feed.url());
    Podcast fresh = new Podcast();
    fresh.setUrl(feed.url());
    podcastParser
        .parseUrlIfModified(fresh, feed.etag(), feed.lastModified())
        .ifPresentOrElse(
            parsed -> applyFeed(podcastId, parsed),
            () -> log.info("Podcast {} not modified since last refresh", feed.url()));
  }

  /** What is needed to (conditionally) fetch a podcast feed. */
  private record FeedLocation(String url, String etag, String lastModified) {}

  /**
   * Merges a freshly parsed feed into the stored podcast, in its own transaction.
   *
   * @param podcastId the stored podcast to update
   * @param fresh the podcast as parsed from its feed, not attached to any persistence context
   */
  void applyFeed(UUID podcastId, Podcast fresh) {
    TransactionHelper.doInNewTransaction(
        platformTransactionManager,
        false,
        () ->
            podcastRepository
                .findById(podcastId)
                .ifPresent(
                    podcast -> {
                      var result = PodcastFeedMerger.merge(podcast, fresh);
                      log.info(
                          "Done refreshing {}: {} new episodes, {} updated",
                          podcast.getName(),
                          result.added(),
                          result.updated());
                    }));
  }

  /**
   * Generates an OPML 2.0 XML document containing all subscribed podcast feeds.
   *
   * @return OPML XML string
   * @throws OpmlWriteException on failure to produce OPML
   *     <p>javadoc generated by AI
   */
  @Transactional(readOnly = true)
  public String exportPodcasts() throws OpmlWriteException {
    List<Podcast> feeds = podcastRepository.findAll();

    Head head =
        new Head(
            "Podku",
            LocalDateTime.now().toString(),
            null,
            null,
            null,
            null,
            null,
            null,
            null,
            null,
            null,
            null,
            null);

    List<Outline> outlines =
        feeds.stream()
            .map(
                feed ->
                    new Outline(
                        Map.of("type", "rss", "xmlUrl", feed.getUrl(), "title", feed.getName()),
                        Collections.emptyList()))
            .toList();

    Body body = new Body(outlines);

    Opml opml = new Opml("2.0", head, body);

    OpmlWriter writer = new OpmlWriter();

    return writer.write(opml);
  }

  /**
   * Imports podcasts from an uploaded OPML multipart file.
   *
   * @param file OPML file
   * @return list of newly added podcasts
   * @throws IOException on file I/O errors
   * @throws OpmlParseException on malformed OPML
   * @throws SQLException on database errors
   *     <p>javadoc generated by AI
   */
  @Transactional
  public List<Podcast> importPodcasts(MultipartFile file)
      throws IOException, OpmlParseException, SQLException {
    log.info("Importing feed");
    Path tempDirectory = Files.createTempDirectory("newsku-opml-import");
    Path p = tempDirectory.resolve("import.opml");
    file.transferTo(p);
    List<Podcast> newPodcasts = new ArrayList<>();

    try (var is = new FileInputStream(p.toFile())) {
      var parser = new OpmlParser().parse(is);
      for (Outline outline : parser.getBody().getOutlines()) {
        newPodcasts.addAll(importPodcast(outline));
      }

      podcastRepository.saveAll(newPodcasts);

      return newPodcasts;
    } catch (SQLException | OpmlParseException e) {
      log.error("Failed to parse opml file", e);
      throw e;
    } finally {
      Files.deleteIfExists(p);
      Files.deleteIfExists(tempDirectory);
    }
  }

  /**
   * Recursively imports a podcast from an OPML outline element and its children.
   *
   * @param outline OPML outline node
   * @return list of parsed podcasts
   * @throws SQLException on database errors
   * @throws IOException on parsing or fetching errors
   *     <p>javadoc generated by AI
   */
  @Transactional
  public List<Podcast> importPodcast(Outline outline) throws SQLException, IOException {
    List<Podcast> newPodcasts = new ArrayList<>();

    Map<String, String> attributes = outline.getAttributes();
    if (attributes.containsKey("type")
        && attributes.get("type").equalsIgnoreCase("rss")
        && attributes.containsKey("xmlUrl")) {
      // we check if the feed already exists
      String url = attributes.get("xmlUrl");
      if (podcastRepository.findFirstByUrl(url).isEmpty()) {
        try {
          Podcast podcast = new Podcast();
          podcast.setUrl(url);
          podcast = podcastParser.parseUrl(podcast);
          newPodcasts.add(podcast);
        } catch (Exception e) {
          log.warn("Couldnt parse podcast {}", url, e);
        }
      } else {
        log.info("User already has podcast {}", url);
      }
    }

    if (!outline.getSubElements().isEmpty()) {
      outline
          .getSubElements()
          .forEach(
              outline1 -> {
                try {
                  newPodcasts.addAll(importPodcast(outline1));
                } catch (SQLException | IOException e) {
                  throw new RuntimeException(e);
                }
              });
    }

    return newPodcasts;
  }

  /**
   * Downloads audio files for recently published episodes up to the configured cache limit and
   * prunes old files.
   *
   * <p>javadoc generated by AI
   */
  public void downloadEpisodes() {
    if (episodeCacheCount > 0) {
      log.info("Starting to cache episodes locally");
      // the downloads happen outside the transaction so no DB connection is held meanwhile
      var episodes =
          TransactionHelper.doInNewTransaction(
              platformTransactionManager,
              true,
              () ->
                  episodeRepository.getEpisodeByPubDateMillisBefore(
                      System.currentTimeMillis(),
                      Sort.by(Sort.Direction.DESC, "pubDateMillis"),
                      Limit.of(episodeCacheCount)));

      for (var e : episodes) {
        try {
          EpisodeUtils.downloadEpisode(e, episodeCacheFolder);
        } catch (IOException ex) {
          log.error("Failed to download episode {}", e.getTitle(), ex);
        }
      }

      List<String> episodeHashes =
          episodes.stream()
              .map(
                  e ->
                      Hashing.sha256()
                          .hashString(e.getAudioUrl(), StandardCharsets.UTF_8)
                          .toString())
              .toList();

      try (var files = Files.list(episodeCacheFolder)) {
        files.forEach(
            path -> {
              File file = path.getFileName().toFile();
              String name = file.getName();
              if (!episodeHashes.contains(name)) {
                log.info("Deleting episode: {}", name);
                try {
                  Files.deleteIfExists(path);
                } catch (IOException e) {
                  log.error("Couldn't delete episode {}", name, e);
                }
              }
            });
      } catch (IOException e) {
        throw new RuntimeException(e);
      }
    }
  }

  /**
   * Searches local podcasts matching a free-text search query using Postgres full-text indexing.
   *
   * @param query search query
   * @param limit maximum results
   * @return list of matching podcasts
   *     <p>javadoc generated by AI
   */
  @Transactional(readOnly = true)
  public List<Podcast> searchPodcasts(String query, int limit) {
    String tsQuery =
        Arrays.stream(query.trim().split("\\s+"))
            .filter(s -> !s.isBlank())
            .map(s -> s.replaceAll("[^a-zA-Z0-9]", "") + ":*")
            .collect(Collectors.joining(" & "));

    if (tsQuery.isBlank()) {
      return List.of();
    }
    return podcastRepository.searchPodcasts(tsQuery, limit);
  }
}
