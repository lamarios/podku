package com.github.lamarios.podku;

import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;
import org.springframework.web.servlet.config.annotation.CorsRegistry;
import org.springframework.web.servlet.config.annotation.WebMvcConfigurer;

/** Application-wide configuration: CORS rules for the REST endpoints. */
@Configuration
public class Config {
  /**
   * Registers the CORS policy: the health endpoint is reachable with GET/OPTIONS only, while every
   * other path accepts the full set of methods used by the frontends.
   *
   * <p>javadoc generated by AI
   */
  @Bean
  public WebMvcConfigurer corsConfigurer() {
    return new WebMvcConfigurer() {
      /**
       * Configures CORS mappings for endpoints.
       *
       * <p>javadoc generated by AI
       */
      @Override
      public void addCorsMappings(CorsRegistry registry) {
        registry
            .addMapping("/actuator/health")
            .allowedOriginPatterns("*")
            .allowedMethods("GET", "OPTIONS");

        registry
            // apply to all endpoints
            .addMapping("/**")
            // frontend URLs
            .allowedOriginPatterns("*")
            .allowedMethods("GET", "POST", "PUT", "DELETE", "OPTIONS", "HEAD")
            .allowedHeaders("*")
            .allowCredentials(true);
      }
    };
  }
}
