package com.github.lamarios.podku.episodes;

import com.fasterxml.jackson.annotation.JsonIgnore;
import com.github.lamarios.podku.utils.FastUrlCrypto;
import jakarta.persistence.*;
import java.util.UUID;

@Entity
@Table(name = "episode_files")
public class EpisodeFile {
  @Id
  @GeneratedValue(strategy = GenerationType.UUID)
  private UUID id;

  private String url;

  @Enumerated(EnumType.STRING)
  private EpisodeFileType type;

  private String mime;
  private String language;
  private String rel;

  // media (audio/video) attributes, from <enclosure> and <podcast:alternateEnclosure>
  private Long lengthBytes;
  private Double bitrate;
  private Integer height;
  private String title;
  private String codecs;
  private Boolean defaultMedia;

  @ManyToOne
  @JoinColumn(name = "episode_id")
  @JsonIgnore
  private Episode episode;

  @Transient private String urlEncrypted;

  /**
   * Gets or generates the encrypted file URL.
   *
   * @return encrypted file URL
   * @throws Exception if encryption fails
   */
  public String getUrlEncrypted() throws Exception {
    if (urlEncrypted != null) {
      return urlEncrypted;
    } else {
      return FastUrlCrypto.instance.encrypt(url);
    }
  }

  /**
   * Sets the encrypted file URL.
   *
   * @param urlEncrypted encrypted file URL
   */
  public void setUrlEncrypted(String urlEncrypted) {
    this.urlEncrypted = urlEncrypted;
  }

  /**
   * Gets the file UUID.
   *
   * @return UUID
   *     <p>javadoc generated by AI
   */
  public UUID getId() {
    return id;
  }

  /**
   * Sets the file UUID.
   *
   * @param id UUID
   *     <p>javadoc generated by AI
   */
  public void setId(UUID id) {
    this.id = id;
  }

  /**
   * Gets the file URL.
   *
   * @return file URL string
   *     <p>javadoc generated by AI
   */
  public String getUrl() {
    return url;
  }

  /**
   * Sets the file URL.
   *
   * @param url file URL string
   *     <p>javadoc generated by AI
   */
  public void setUrl(String url) {
    this.url = url;
  }

  /**
   * Gets the episode file type (transcript, chapters, audio, video).
   *
   * @return file type
   *     <p>javadoc generated by AI
   */
  public EpisodeFileType getType() {
    return type;
  }

  /**
   * Sets the episode file type.
   *
   * @param type file type
   *     <p>javadoc generated by AI
   */
  public void setType(EpisodeFileType type) {
    this.type = type;
  }

  /**
   * Gets the MIME type of the file.
   *
   * @return MIME type string
   *     <p>javadoc generated by AI
   */
  public String getMime() {
    return mime;
  }

  /**
   * Sets the MIME type of the file.
   *
   * @param mime MIME type string
   *     <p>javadoc generated by AI
   */
  public void setMime(String mime) {
    this.mime = mime;
  }

  /**
   * Gets the language tag for this file.
   *
   * @return language code
   *     <p>javadoc generated by AI
   */
  public String getLanguage() {
    return language;
  }

  /**
   * Sets the language tag for this file.
   *
   * @param language language code
   *     <p>javadoc generated by AI
   */
  public void setLanguage(String language) {
    this.language = language;
  }

  /**
   * Gets the relationship attribute of the file.
   *
   * @return rel string
   *     <p>javadoc generated by AI
   */
  public String getRel() {
    return rel;
  }

  /**
   * Sets the relationship attribute of the file.
   *
   * @param rel rel string
   *     <p>javadoc generated by AI
   */
  public void setRel(String rel) {
    this.rel = rel;
  }

  /**
   * Gets the media file size in bytes.
   *
   * @return file size in bytes, null if unknown or not a media file
   */
  public Long getLengthBytes() {
    return lengthBytes;
  }

  /**
   * Sets the media file size in bytes.
   *
   * @param lengthBytes file size in bytes
   */
  public void setLengthBytes(Long lengthBytes) {
    this.lengthBytes = lengthBytes;
  }

  /**
   * Gets the media encoding bitrate.
   *
   * @return bitrate, null if unknown or not a media file
   */
  public Double getBitrate() {
    return bitrate;
  }

  /**
   * Sets the media encoding bitrate.
   *
   * @param bitrate bitrate
   */
  public void setBitrate(Double bitrate) {
    this.bitrate = bitrate;
  }

  /**
   * Gets the video height in pixels.
   *
   * @return height, null if unknown or not a video file
   */
  public Integer getHeight() {
    return height;
  }

  /**
   * Sets the video height in pixels.
   *
   * @param height height in pixels
   */
  public void setHeight(Integer height) {
    this.height = height;
  }

  /**
   * Gets the human readable title of the media variant, e.g. "Standard".
   *
   * @return title, null if none
   */
  public String getTitle() {
    return title;
  }

  /**
   * Sets the human readable title of the media variant.
   *
   * @param title title
   */
  public void setTitle(String title) {
    this.title = title;
  }

  /**
   * Gets the RFC 6381 codecs string of the media.
   *
   * @return codecs, null if unknown
   */
  public String getCodecs() {
    return codecs;
  }

  /**
   * Sets the RFC 6381 codecs string of the media.
   *
   * @param codecs codecs
   */
  public void setCodecs(String codecs) {
    this.codecs = codecs;
  }

  /**
   * Whether this media is the feed's default one, i.e. the item's main {@code <enclosure>}.
   *
   * @return true for the default media, null if not a media file
   */
  public Boolean getDefaultMedia() {
    return defaultMedia;
  }

  /**
   * Sets whether this media is the feed's default one.
   *
   * @param defaultMedia default flag
   */
  public void setDefaultMedia(Boolean defaultMedia) {
    this.defaultMedia = defaultMedia;
  }

  /**
   * Gets the owning episode.
   *
   * @return episode entity
   *     <p>javadoc generated by AI
   */
  public Episode getEpisode() {
    return episode;
  }

  /**
   * Sets the owning episode.
   *
   * @param episode episode entity
   *     <p>javadoc generated by AI
   */
  public void setEpisode(Episode episode) {
    this.episode = episode;
  }
}
