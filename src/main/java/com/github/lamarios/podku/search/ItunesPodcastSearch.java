package com.github.lamarios.podku.search;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.github.lamarios.podku.utils.VibrantColorExtractor;
import java.io.IOException;
import java.net.URI;
import java.net.URLEncoder;
import java.net.http.HttpClient;
import java.net.http.HttpRequest;
import java.net.http.HttpResponse;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.List;
import java.util.stream.Collectors;
import org.apache.logging.log4j.LogManager;
import org.apache.logging.log4j.Logger;
import org.springframework.stereotype.Service;

/** Thin client for the iTunes Search API, scoped to podcasts. */
@Service
public class ItunesPodcastSearch {
  private final Logger log = LogManager.getLogger();
  private static final String SEARCH_URL = "https://itunes.apple.com/search";
  private static final String LOOKUP_URL = "https://itunes.apple.com/lookup";
  private final HttpClient client;
  private final ObjectMapper objectMapper;

  /**
   * Default constructor configuring standard HTTP client and object mapper.
   *
   * <p>javadoc generated by AI
   */
  public ItunesPodcastSearch() {
    this(HttpClient.newHttpClient(), new ObjectMapper());
  }

  /**
   * Constructs an ItunesPodcastSearch with specified HTTP client and object mapper.
   *
   * @param client HTTP client
   * @param objectMapper Jackson object mapper
   *     <p>javadoc generated by AI
   */
  public ItunesPodcastSearch(HttpClient client, ObjectMapper objectMapper) {
    this.client = client;
    this.objectMapper = objectMapper;
  }

  /**
   * Searches the iTunes podcast directory.
   *
   * @param term search string (name, author, etc.)
   * @param country ISO 2-letter country code, defaults to "US"
   * @param limit max results, defaults to 25 (Apple's API default is 50)
   * @return list of search results enriched with colors
   *     <p>javadoc generated by AI
   */
  public List<SearchResult> search(String term, String country, Integer limit) {
    return withColors(searchWithoutColors(term, country, limit));
  }

  /**
   * Searches the iTunes podcast directory without computing artwork colors, which requires
   * downloading every artwork. Use {@link #withColors(List)} on the results that are kept.
   *
   * @param term search string (name, author, etc.)
   * @param country ISO 2-letter country code, defaults to "US"
   * @param limit max results, defaults to 50
   * @return list of search results without colors
   */
  public List<SearchResult> searchWithoutColors(String term, String country, Integer limit) {
    String country_ = country != null ? country : "US";
    int limit_ = limit != null ? limit : 50;

    String query =
        "term="
            + encode(term)
            + "&media=podcast"
            + "&entity=podcast"
            + "&country="
            + encode(country_)
            + "&limit="
            + limit_;

    return parseResults(get(URI.create(SEARCH_URL + "?" + query), "iTunes search"));
  }

  /**
   * Computes the vibrant artwork color of each result, in parallel.
   *
   * @param results the results to enrich
   * @return the same results, with their color set when it could be computed
   */
  public List<SearchResult> withColors(List<SearchResult> results) {
    return results.parallelStream()
        .peek(
            r -> {
              try {
                r.setColor(VibrantColorExtractor.extractVibrantColorHex(r.getArtworkUrl()));
              } catch (Exception e) {
                log.error("Could not get image color", e);
              }
            })
        .collect(Collectors.toList());
  }

  /**
   * Looks up several podcasts by their iTunes collection IDs in a single request.
   *
   * @param collectionIds the iTunes collection identifiers
   * @return the podcasts found, without colors
   */
  public List<SearchResult> lookupByIds(List<Long> collectionIds) {
    if (collectionIds.isEmpty()) {
      return new ArrayList<>();
    }
    String ids = collectionIds.stream().map(String::valueOf).collect(Collectors.joining(","));
    String query = "id=" + ids + "&entity=podcast";
    return parseResults(get(URI.create(LOOKUP_URL + "?" + query), "iTunes lookup"));
  }

  /**
   * Returns the iTunes collection IDs of the top podcasts of a genre, from Apple's top charts.
   *
   * @param genreId the iTunes genre identifier (e.g. 1318 for Technology)
   * @param country ISO 2-letter country code
   * @param limit maximum number of podcasts to return
   * @return the collection IDs, best ranked first
   */
  public List<Long> topPodcastIds(String genreId, String country, int limit) {
    URI uri =
        URI.create(
            "https://itunes.apple.com/"
                + encode(country.toLowerCase())
                + "/rss/toppodcasts/limit="
                + limit
                + "/genre="
                + encode(genreId)
                + "/json");
    JsonNode entries = get(uri, "iTunes top podcasts").path("feed").path("entry");

    List<Long> ids = new ArrayList<>();
    // a chart with a single podcast has its entry as an object instead of an array
    for (JsonNode entry : entries.isArray() ? entries : List.of(entries)) {
      String id = entry.path("id").path("attributes").path("im:id").asText(null);
      if (id != null) {
        try {
          ids.add(Long.parseLong(id));
        } catch (NumberFormatException e) {
          log.warn("Invalid podcast id in iTunes top podcasts: {}", id);
        }
      }
    }
    return ids;
  }

  /**
   * Converts the {@code results} array of an iTunes search or lookup response.
   *
   * @param body the parsed response
   * @return the results, without colors
   */
  private List<SearchResult> parseResults(JsonNode body) {
    List<SearchResult> results = new ArrayList<>();
    JsonNode resultsNode = body.get("results");
    if (resultsNode != null && resultsNode.isArray()) {
      for (JsonNode r : resultsNode) {
        results.add(objectMapper.convertValue(r, SearchResult.class));
      }
    }
    return results;
  }

  /**
   * Searches the iTunes podcast directory using default country code US.
   *
   * @param term search query string
   * @param limit maximum results to return
   * @return list of search results
   *     <p>javadoc generated by AI
   */
  public List<SearchResult> search(String term, int limit) {
    return search(term, "US", limit);
  }

  /**
   * Looks up a single podcast by its iTunes collection ID.
   *
   * @param collectionId the iTunes collection identifier
   * @return the search result or null if not found
   *     <p>javadoc generated by AI
   */
  public SearchResult lookupById(long collectionId) {
    String query = "id=" + collectionId + "&entity=podcast";
    JsonNode body = get(URI.create(LOOKUP_URL + "?" + query), "iTunes lookup");

    JsonNode resultsNode = body.get("results");
    if (resultsNode == null || !resultsNode.isArray() || resultsNode.isEmpty()) {
      return null;
    }
    return objectMapper.convertValue(resultsNode.get(0), SearchResult.class);
  }

  /**
   * Sends an HTTP GET request to iTunes API and parses the JSON response.
   *
   * @param uri the request URI
   * @param context description for logging/error context
   * @return parsed JsonNode root
   *     <p>javadoc generated by AI
   */
  private JsonNode get(URI uri, String context) {
    try {
      HttpRequest request = HttpRequest.newBuilder(uri).GET().build();
      HttpResponse<String> response = client.send(request, HttpResponse.BodyHandlers.ofString());

      if (response.statusCode() != 200) {
        throw new ItunesSearchException(context + " failed with status " + response.statusCode());
      }
      return objectMapper.readTree(response.body());
    } catch (IOException e) {
      throw new ItunesSearchException(context + " failed: " + e.getMessage());
    } catch (InterruptedException e) {
      Thread.currentThread().interrupt();
      throw new ItunesSearchException(context + " interrupted");
    }
  }

  /**
   * URL-encodes a string in UTF-8.
   *
   * @param value string to encode
   * @return URL-encoded string
   *     <p>javadoc generated by AI
   */
  private static String encode(String value) {
    return URLEncoder.encode(value, StandardCharsets.UTF_8);
  }
}
